// Local image generation through ComfyUI (runtime/comfyui), fully offline:
//   · started on demand on 127.0.0.1 with model paths inside models/image-generation (no other model folders)
//   · one image at a time (6 GB GPU), sampler step progress read live from ComfyUI's websocket
//   · images cached by (model, workflow, prompt, negative, seed, size): identical requests are reused
//   · per-shot regeneration (new seed) and approval are recorded in generated-images/index.json
//   · VRAM is released after the stage so WebGL frame capture has the GPU
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawn } from 'node:child_process';
import { PATHS, ROOT, STUDIO_CONFIG, childEnv } from './workspace.js';
import { getCatalog } from './catalog.js';
import { killTree } from './jobs.js';
import { runtimeProfile } from './setup/settings.js';

const PORT = STUDIO_CONFIG.services.comfyPort || 8188, BASE = `http://127.0.0.1:${PORT}`;
const WORKFLOW = path.join(PATHS.comfyWorkflows, 'sd15-txt2img.json');
const EXTRA_PATHS = path.join(ROOT, 'config', 'comfyui-extra-model-paths.yaml');
let proc = null, starting = null, idleTimer = null;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

export const DEFAULT_SETTINGS = { width: 512, height: 912, steps: 22, cfg: 6.5, sampler: 'dpmpp_2m', scheduler: 'karras', hires: true, hiresScale: 1.5, hiresSteps: 12, hiresDenoise: 0.45 };
export function settings() { const c = getCatalog()._internal.comfy; return { ...DEFAULT_SETTINGS, ...(c.settings || {}) }; }

async function alive() { try { return (await fetch(`${BASE}/system_stats`, { signal: AbortSignal.timeout(1500) })).ok; } catch { return false; } }

export async function ensureComfy(onStatus = () => {}) {
  clearTimeout(idleTimer);
  if (proc && proc.exitCode === null && await alive()) return;
  if (starting) return starting;
  const c = getCatalog(true)._internal.comfy;
  if (!c.ready) throw new Error(`ComfyUI unavailable: ${c.reason}`);
  const base = PATHS.models.imageGeneration.split(path.sep).join('/');
  fs.writeFileSync(EXTRA_PATHS, `# generated by the studio: ComfyUI reads models only from the workspace\nstudio:\n  base_path: "${base}"\n  checkpoints: checkpoints\n  loras: loras\n  vae: vae\n  embeddings: embeddings\n`);
  starting = (async () => {
    onStatus('Starting ComfyUI (local)');
    const log = [];
    proc = spawn(c.python, [path.join(PATHS.comfyui, 'main.py'), '--listen', '127.0.0.1', '--port', String(PORT), '--extra-model-paths-config', EXTRA_PATHS, '--disable-auto-launch', '--preview-method', 'none', '--offline', '--disable-all-custom-nodes', ...(runtimeProfile().comfyArgs || [])],
      { cwd: PATHS.comfyui, env: childEnv(), windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
    const keep = (b) => { log.push(...b.toString().split(/\r?\n/).filter(Boolean)); if (log.length > 80) log.splice(0, log.length - 80); };
    proc.stdout.on('data', keep); proc.stderr.on('data', keep);
    for (let i = 0; i < 360; i++) {
      if (proc.exitCode !== null) throw new Error(`ComfyUI exited (${proc.exitCode}): ${log.slice(-8).join(' | ')}`);
      if (await alive()) { onStatus('ComfyUI ready'); return; }
      await sleep(500);
    }
    throw new Error('ComfyUI did not start within 180 s');
  })();
  try { await starting; } finally { starting = null; }
}
export async function freeVram() { try { await fetch(`${BASE}/free`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ unload_models: true, free_memory: true }) }); } catch {} }
export function stopComfy() { clearTimeout(idleTimer); if (proc) { killTree(proc, { sync: true }); proc = null; } }
process.on('exit', () => { if (proc) killTree(proc, { sync: true }); });
function scheduleIdleStop() { clearTimeout(idleTimer); idleTimer = setTimeout(stopComfy, 5 * 60_000); }

function buildPrompt({ checkpoint, positive, negative, seed, prefix, s }) {
  const wf = JSON.parse(fs.readFileSync(WORKFLOW, 'utf8'));
  const vals = { checkpoint, positive, negative, seed, prefix, ...s, decodeFrom: s.hires ? '7' : '5' };
  const fill = (v) => {
    if (typeof v === 'string') { const m = v.match(/^\{\{(\w+)\}\}$/); if (m) return vals[m[1]]; return v.replace(/\{\{(\w+)\}\}/g, (_, k) => String(vals[k])); }
    if (Array.isArray(v)) return v.map(fill);
    if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, fill(x)]));
    return v;
  };
  const p = fill(wf.prompt);
  if (!s.hires) { delete p['6']; delete p['7']; }
  return { prompt: p, workflowVersion: wf.version };
}

export const seedFor = (text, salt = 0) => parseInt(crypto.createHash('sha1').update(`${text}#${salt}`).digest('hex').slice(0, 8), 16);

/** generate (or reuse from cache) one image. onStep({ current, total }) reports real sampler steps. */
// an occasional ComfyUI run ends without an image (history written after the "finished" event, or a transient
// websocket/execution error): retry the same request up to 2 more times before failing the render
export async function generateImage(opts) {
  for (let attempt = 1; ; attempt++) {
    try { return await generateOnce(opts); }
    catch (e) { if (e.cancelled || attempt >= 3 || /rejected the workflow/.test(e.message)) throw e; console.warn(`image attempt ${attempt} failed (${e.message}); retrying`); await new Promise((r) => setTimeout(r, 1500)); }
  }
}

async function generateOnce({ positive, negative, seed, outFile, prefix, onStep = () => {}, isCancelled = () => false, settingsOverride = null }) {
  const c = getCatalog()._internal.comfy, s = settingsOverride || settings();
  const { prompt, workflowVersion } = buildPrompt({ checkpoint: c.checkpoint, positive, negative, seed, prefix, s });
  const key = crypto.createHash('sha1').update(JSON.stringify([c.checkpoint, workflowVersion, positive, negative, seed, s])).digest('hex').slice(0, 16);
  const cacheDir = path.join(PATHS.models.imageGeneration, 'cache'); fs.mkdirSync(cacheDir, { recursive: true });
  const cached = path.join(cacheDir, `${key}.png`);
  const meta = { key, checkpoint: c.checkpoint, workflow: `engine/comfy-workflows/sd15-txt2img.json v${workflowVersion}`, seed, settings: s, positive, negative };
  if (fs.existsSync(cached)) { fs.copyFileSync(cached, outFile); return { ...meta, cached: true, seconds: 0 }; }
  await ensureComfy();
  const clientId = crypto.randomUUID(), t0 = Date.now();
  const totalSteps = s.steps + (s.hires ? s.hiresSteps : 0); let doneSteps = 0, lastNode = null, base = 0;
  const ws = new WebSocket(`ws://127.0.0.1:${PORT}/ws?clientId=${clientId}`);
  await new Promise((res, rej) => { ws.onopen = res; ws.onerror = () => rej(new Error('ComfyUI websocket failed')); });
  let promptId = null; const finished = new Promise((res, rej) => {
    ws.onmessage = (e) => {
      if (typeof e.data !== 'string') return;
      let m; try { m = JSON.parse(e.data); } catch { return; }
      const d = m.data || {};
      if (promptId && d.prompt_id && d.prompt_id !== promptId) return;
      if (m.type === 'progress') { if (d.node !== lastNode) { base = doneSteps; lastNode = d.node; } doneSteps = Math.max(doneSteps, base + d.value); onStep({ current: Math.min(doneSteps, totalSteps), total: totalSteps }); }
      if (m.type === 'execution_error') rej(new Error(`ComfyUI error in ${d.node_type}: ${d.exception_message}`));
      if (m.type === 'executing' && d.node === null && d.prompt_id === promptId) res();
      if (m.type === 'execution_success' && d.prompt_id === promptId) res();
    };
  });
  try {
    const r = await fetch(`${BASE}/prompt`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ prompt, client_id: clientId }) });
    const j = await r.json(); if (!r.ok || j.error) throw new Error(`ComfyUI rejected the workflow: ${JSON.stringify(j.error || j.node_errors || j).slice(0, 300)}`);
    promptId = j.prompt_id;
    const poll = setInterval(async () => { if (isCancelled()) { clearInterval(poll); try { await fetch(`${BASE}/interrupt`, { method: 'POST' }); } catch {} } }, 500);
    try { await finished; } finally { clearInterval(poll); }
    if (isCancelled()) throw Object.assign(new Error('Job cancelled by user'), { cancelled: true });
    let img = null;
    for (let k = 0; k < 20 && !img; k++) {   // history can lag the finished event by a moment
      const h = await (await fetch(`${BASE}/history/${promptId}`)).json();
      img = Object.values(h[promptId]?.outputs || {}).flatMap((o) => o.images || [])[0];
      if (!img) await new Promise((r) => setTimeout(r, 500));
    }
    if (!img) throw new Error('ComfyUI finished without an image');
    const buf = Buffer.from(await (await fetch(`${BASE}/view?filename=${encodeURIComponent(img.filename)}&subfolder=${encodeURIComponent(img.subfolder)}&type=${img.type}`)).arrayBuffer());
    fs.writeFileSync(outFile, buf); fs.writeFileSync(cached, buf);
    return { ...meta, cached: false, seconds: +((Date.now() - t0) / 1000).toFixed(1) };
  } finally { try { ws.close(); } catch {} scheduleIdleStop(); }
}

// ── per-project image index (cache, regeneration, approval) ───────────────────────────────────────────────
export function imageIndexPath(projectDir) { return path.join(projectDir, 'generated-images', 'index.json'); }
export function readImageIndex(projectDir) { try { return JSON.parse(fs.readFileSync(imageIndexPath(projectDir), 'utf8')); } catch { return { shots: {} }; } }
export function writeImageIndex(projectDir, idx) { fs.writeFileSync(imageIndexPath(projectDir), JSON.stringify(idx, null, 2)); }
